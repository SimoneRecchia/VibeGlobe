// Writes THIRD_PARTY_NOTICES.md from the dependencies shipped in the published packages; `--check` fails when the
// committed file is stale.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { readShippedPackages } from './shipped-dependencies.ts';
import { ROOT_DIR } from './workspace.ts';

const NOTICES_PATH = join(ROOT_DIR, 'THIRD_PARTY_NOTICES.md');

function licenseText(packagePath: string): string | undefined {
  const dir = join(ROOT_DIR, packagePath);
  if (!existsSync(dir)) return undefined;
  const file = readdirSync(dir)
    .sort()
    .find((name) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : undefined;
}

const packages = readShippedPackages();
const sections = packages.map((pkg) => {
  const text =
    licenseText(pkg.path) ?? `The package ships no license file; its declared license is ${pkg.license ?? 'missing'}.`;
  return `## ${pkg.name} ${pkg.version}\n\nLicense: ${pkg.license ?? 'missing'}\n\n\`\`\`text\n${text}\n\`\`\`\n`;
});
const notices = [
  '# Third-party notices',
  '',
  'Generated by `npm run notices` from the third-party packages shipped with the published VibeGlobe packages. Do not edit by hand.',
  '',
  ...(sections.length === 0 ? ['The published packages have no third-party runtime dependencies.', ''] : sections),
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(NOTICES_PATH) ? readFileSync(NOTICES_PATH, 'utf8') : '';
  if (current !== notices) {
    console.error('THIRD_PARTY_NOTICES.md is stale: run `npm run notices` and commit the result.');
    process.exit(1);
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.');
} else {
  writeFileSync(NOTICES_PATH, notices);
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages).`);
}
